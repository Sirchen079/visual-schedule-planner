const fs = require('fs'), path = require('path'), assert = require('node:assert/strict')
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))

async function run({ mainWindow, widget, getJson }) {
  const mode = process.env.ZHISHI_SETTINGS_SMOKE
  const qa = process.env.ZHISHI_SETTINGS_QA
  if (!process.env.ZHISHI_SHELL_USER_DATA_DIR || !process.env.ZHISHI_SHELL_DATA_DIR || !qa || !['seed','check'].includes(mode)) throw Error('设置自检必须显式隔离资料目录并指定 seed/check')
  const js = code => mainWindow.webContents.executeJavaScript(code, true)
  async function wait(code) {for(let i=0;i<180;i++){if(await js(code))return;await delay(100)}throw Error('Timeout '+code)}
  async function click(selector) {await js(`document.querySelector(${JSON.stringify(selector)}).click()`);await delay(120)}
  async function fill(label,value) {await js(`(()=>{const e=document.querySelector('[aria-label=${JSON.stringify(label)}]');if(!e)throw Error('Missing input');e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('input',{bubbles:true}));e.dispatchEvent(new Event('change',{bubbles:true}))})()`)}
  async function shot(name) {
    await js(`document.querySelector('.bell[data-open="true"]')?.click()`)
    await delay(350);fs.writeFileSync(path.join(qa,name+'.png'),(await mainWindow.webContents.capturePage()).toPNG())
  }
  const errors=[]
  mainWindow.webContents.on('console-message',(_e,level,message)=>{if(level>=2&&!message.includes('Electron Security Warning'))errors.push(message)})
  await js(`location.hash='/settings?section=desktop'`)
  await wait(`Boolean(window.zhishiDesktop&&document.getElementById('pref-widget-visible'))`)
  assert.equal(await js(`document.querySelector('.nav-settings-label').textContent`),'设置')
  if(mode==='check') {
    assert.deepEqual(await js('window.zhishiDesktop.preferences().then(s=>[s.visible,s.pinned,s.collapsed,s.notifications])'),[false,false,true,false])
    assert.equal(widget.isVisible(),false);assert.equal(widget.getWindow(),null)
    assert.equal(await js(`document.querySelector('#pref-widget-visible').getAttribute('aria-checked')`),'false')
    const configs=await getJson('/ai/configs')
    assert.equal(configs.length,1);assert.equal(configs[0].context_window,128000)
    assert.equal(configs[0].reasoning_effort,'low');assert.equal(configs[0].max_output_tokens,4096);assert.deepEqual(configs[0].input_modalities,['text','image'])
    assert.equal(configs[0].has_api_key,true)
    const services=await getJson('/ai/web-services')
    assert.equal(services.config.search_provider,'builtin');assert.equal(services.config.fetch_provider,'builtin')
    assert.equal(services.tavily_has_api_key,false);assert.equal((await getJson('/ai/vision')).enabled,false)
    assert.deepEqual(errors,[])
    fs.writeFileSync(path.join(qa,'settings-restart.json'),JSON.stringify({passed:true,errors,checks:['visibility, pin, collapsed and notification persistence','hidden widget not created at restart']}))
    await require('./event-reminders-selftest').run({mainWindow,getJson,qa,mode})
    console.log('SETTINGS_RESTART_PASS');return
  }
  mainWindow.setSize(1450,1000)
  widget.show()
  const win=widget.getWindow(), wjs=code=>win.webContents.executeJavaScript(code,true)
  for(let i=0;i<150;i++){if(!win.webContents.isLoading()&&await wjs(`Boolean(document.querySelector('#widget-settings'))`))break;await delay(100)}
  await js(`location.hash='/'`);await delay(100)
  await wjs(`document.getElementById('widget-settings').click()`)
  await wait(`location.hash.includes('/settings?section=desktop')&&!!document.getElementById('pref-widget-visible')`)
  await click('#pref-widget-visible');assert.equal(win.isVisible(),false)
  await click('#pref-widget-pinned');assert.equal(win.isAlwaysOnTop(),false)
  await click('#pref-widget-collapsed');assert.equal(win.getBounds().height,78)
  assert.equal(await wjs(`document.querySelector('.widget-shell').classList.contains('collapsed')`),true)
  await click('#pref-widget-visible');assert.equal(win.isVisible(),true)
  await click('#pref-widget-collapsed');assert.equal(win.getBounds().height,680)
  assert.equal(await wjs(`document.querySelector('.widget-shell').classList.contains('collapsed')`),false)
  await wjs(`document.getElementById('widget-pin').click()`)
  await wait(`document.getElementById('pref-widget-pinned').getAttribute('aria-checked')==='true'`)
  await click('#pref-widget-reset')
  assert(win.getBounds().x>=0)
  await click('#pref-notifications')
  assert.equal(await js(`window.zhishiDesktop.preferences().then(s=>s.notifications)`),false)
  const followup=`button[aria-label="学习与研究持续跟进"]`
  await click(followup)
  assert.equal((await getJson('/api/settings')).feature_followup_enabled,'false')
  await click(followup)
  assert.equal((await getJson('/api/settings')).feature_followup_enabled,'true')
  await js(`document.documentElement.dataset.theme='light'`)
  await shot('settings-desktop-light')
  await js(`document.documentElement.dataset.theme='dark'`)
  await shot('settings-desktop-dark')
  const modelBase=process.env.ZHISHI_MODELS_TEST_URL
  if (!/^http:\/\/127\.0\.0\.1:\d+\/v1$/.test(modelBase||'')) throw Error('模型列表测试只允许显式回环地址')
  await js(`(()=>{const button=[...document.querySelectorAll('.settings-nav button')].find(b=>b.textContent==='AI 模型');button.click();[...document.querySelectorAll('#settings-configs button')].find(b=>b.textContent.trim()==='添加配置').click()})()`)
  await wait(`!!document.getElementById('fetch-models')`)
  await fill('配置名称','模型列表验收')
  await fill('Base URL',modelBase)
  await fill('API Key','disposable-catalog-check')
  await click('#fetch-models')
  await wait(`document.querySelectorAll('#available-models option').length===3`)

  await js(`(()=>{const e=document.getElementById('available-models');e.value='catalog-beta';e.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  assert.equal(await js(`document.querySelector('[aria-label="模型名称"]').value`),'catalog-beta')
  assert.deepEqual(await getJson('/ai/configs'),[])
  await js(`document.getElementById('settings-configs').scrollIntoView({block:'start'});document.documentElement.dataset.theme='light'`)
  await shot('settings-model-list-light')
  await fill('API Key','bad-catalog-key')
  await click('#fetch-models')
  await wait(`document.querySelector('#settings-configs .form-error')?.textContent.includes('认证失败')`)
  assert.equal(await js(`document.querySelector('[aria-label="API Key"]').value`),'bad-catalog-key')
  assert.equal(await js(`document.querySelector('[aria-label="模型名称"]').value`),'catalog-beta')
  await fill('API Key','disposable-catalog-check')
  await click('#fetch-models')
  await wait(`document.querySelectorAll('#available-models option').length===3`)
  await js(`(()=>{for(const [id,value] of [['config-context-window','128000'],['config-max-output','8192']]){const e=document.getElementById(id);e.value=value;e.dispatchEvent(new Event('input',{bubbles:true}))}document.querySelector('.modality-option input[value="image"]').click()})()`)
  await click('#settings-configs button[type="submit"]')
  await wait(`!document.querySelector('#settings-configs .inline-form')`)
  let configured=await getJson('/ai/configs')
  assert.equal(configured[0].reasoning_effort,null)
  assert.equal(configured.length,1);assert.equal(configured[0].context_window,128000)
  assert.equal(configured[0].max_output_tokens,8192);assert.deepEqual(configured[0].input_modalities,['text','image'])
  await js(`(()=>{[...document.querySelectorAll('#settings-configs .items button')].find(b=>b.textContent.trim()==='编辑').click()})()`)
  await wait(`!!document.getElementById('config-max-output')`)
  assert.equal(await js(`document.querySelector('[aria-label="API Key"]').value`),'')
  assert.equal(await js(`document.getElementById('config-context-window').value`),'128000')
  await click('#fetch-models')
  await wait(`document.querySelectorAll('#available-models option').length===3`)
  await js(`(()=>{const e=document.getElementById('config-max-output');e.value='4096';e.dispatchEvent(new Event('input',{bubbles:true}));document.querySelector('.capabilities').scrollIntoView({block:'center'});document.documentElement.dataset.theme='light'})()`)
  await js(`(()=>{const e=document.getElementById('config-reasoning-effort');e.value='low';e.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await shot('settings-model-capabilities-light')
  await js(`document.documentElement.dataset.theme='dark'`)
  await shot('settings-model-capabilities-dark')
  await click('#settings-configs button[type="submit"]')
  await wait(`!document.querySelector('#settings-configs .inline-form')`)
  configured=await getJson('/ai/configs')
  assert.equal(configured[0].reasoning_effort,'low');assert.equal(configured[0].max_output_tokens,4096);assert.equal(configured[0].has_api_key,true)
  await js(`location.hash='/settings?section=network'`)
  await wait(`!!document.getElementById('network-web-save')`)
  assert.equal(await js(`document.getElementById('network-search-provider').value`),'builtin')
  await js(`(()=>{const e=document.getElementById('network-search-provider');e.value='tavily';e.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await click('#network-web-save')
  await wait(`document.querySelector('#network-preferences-root').textContent.includes('请先保存 Tavily API Key')`)
  assert.equal((await getJson('/ai/web-services')).config.search_provider,'builtin')
  await fill('Tavily API Key','disposable-tavily-ui-check')
  await click('#network-preferences-root .credentials .save-row button')
  await wait(`document.querySelector('#network-preferences-root .credentials .badge').textContent==='已配置'`)
  assert.equal(await js(`document.getElementById('network-tavily-key').value`),'')
  await click('#network-web-save')
  await wait(`document.querySelector('#network-web-save').nextElementSibling.textContent.includes('已保存')`)
  assert.equal((await getJson('/ai/web-services')).config.search_provider,'tavily')
  assert.equal((await getJson('/ai/web-services')).config.fetch_provider,'builtin')
  await js(`(()=>{const e=document.getElementById('network-search-provider');e.value='builtin';e.dispatchEvent(new Event('change',{bubbles:true}))})()`)
  await click('#network-web-save')
  await wait(`document.querySelector('#network-web-save').nextElementSibling.textContent.includes('已保存')`)
  await click('#network-preferences-root .credentials .remove')
  await wait(`document.querySelector('#network-preferences-root .credentials .badge').textContent==='未配置'`)
  await click('#network-vision-enabled');await click('#network-vision-save')
  await wait(`document.getElementById('network-preferences-root').textContent.includes('请选择已有的 MCP 服务器')`)
  assert.equal((await getJson('/ai/vision')).enabled,false)
  await click('#network-vision-enabled');await click('#network-vision-save')
  await wait(`document.querySelector('#network-vision-save').nextElementSibling.textContent.includes('已关闭')`)
  await js(`document.documentElement.dataset.theme='light';document.getElementById('settings-network').scrollIntoView({block:'start'})`)
  await shot('settings-network-light')
  await js(`document.documentElement.dataset.theme='dark'`)
  await shot('settings-network-dark')
  await js(`location.hash='/board'`);await delay(100)
  await js(`location.hash='/settings?section=desktop'`)
  await wait(`!!document.getElementById('pref-widget-visible')`)
  // Re-entering settings used to fail when its cached data caused an immediate watcher callback.
  mainWindow.setSize(990,850);await delay(300)
  await shot('settings-desktop-narrow')
  assert.equal(await js(`document.documentElement.scrollWidth<=window.innerWidth+2`),true)
  await js(`location.hash='/settings?section=network'`);await delay(300)
  await shot('settings-network-narrow')
  assert.equal(await js(`document.documentElement.scrollWidth<=window.innerWidth+2`),true)
  await require('./event-reminders-selftest').run({mainWindow,getJson,qa,mode})
  for(const [key,value] of [['pinned',false],['collapsed',true],['visible',false],['notifications',false]]) await js(`window.zhishiDesktop.updatePreferences(${JSON.stringify({[key]:value})})`)
  assert.deepEqual(errors,[])
  fs.writeFileSync(path.join(qa,'settings-ui.json'),JSON.stringify({passed:true,errors,checks:['visible Settings entry','widget settings shortcut','hide/show/pin/collapse/reset live window','widget-to-settings state updates','system notification preference','followup switch saves','model catalog fetch/select','authentication error retains inputs','fetch does not save configuration','model capabilities save/edit/persist','saved-key model discovery','independent search/reader provider save','Tavily key save/remove','missing vision server cannot enable','return to settings','dark/light/narrow views']}))
  console.log('SETTINGS_UI_PASS')
}
module.exports={run}
